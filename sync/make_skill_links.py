"""
Generate the Codex skill wrappers that link to the Claude commands.

For each .claude/commands/<name>.md not listed in .agents/claude-only.txt, write
.agents/skills/<name>/SKILL.md: frontmatter (name from the file name, description
from the command's `description:`), plus relative links to the command and to
AGENTS.md. The command text is never copied, and no rule is restated.

Each wrapper is reported as one of:
  created / updated / unchanged   written, rewritten (kit-made only), or already identical
  conflict    exists, differs, and was not made by this script; left untouched
              (--force-wrappers renames it to SKILL.md.pre-agent-kit, then writes)
  stale       a wrapper whose command is gone (or is now Claude-only); left in place
  skipped     the command is listed in .agents/claude-only.txt
  error       the command can't be wrapped (no description, unreadable, bad name)

It never deletes anything. Native skills (a .agents/skills/<name> with no matching
command that doesn't link to one) are ignored.

Exit code: 0 when every wrapper is in place; 1 on any stale, conflict or error, and
with --check also when a wrapper would be created or updated.

Usage: python3 .github/scripts/make_skill_links.py [--repo PATH] [--check] [--force-wrappers]
"""
import argparse
import json
import os
import re
import sys

CMD_DIR = ".claude/commands"
SKILL_DIR = ".agents/skills"
ALLOW_FILE = ".agents/claude-only.txt"
BACKUP_SUFFIX = ".pre-agent-kit"
MARKER = "<!-- agent-kit: generated by make_skill_links.py"
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")

COPYRIGHT = "<!-- Copyright 2026 Tharwat Abdul-Malik. Part of agent-kit (MIT License). -->"

TEMPLATE = """---
name: {name}
description: {description}
---
{copyright}

# {name}

Invocation: `{invocation}`.

Read and follow [the Codex project instructions](../../../AGENTS.md), including the shared `CLAUDE.md` and `CLAUDE.kit.md` rules and the Codex tooling adaptations.

Read [the canonical {name} workflow](../../../.claude/commands/{name}.md) in full, then follow it for the supplied arguments and scope. Read any referenced rules or dependent workflows when their steps require them. This skill is an entry point, not a replacement or abbreviated checklist.

{marker} from .claude/commands/{name}.md. Edit that file and re-run the generator; don't edit this one. -->
"""


# ---------------------------------------------------------------------------
# Frontmatter: just enough YAML to read one scalar key.
# ---------------------------------------------------------------------------
def frontmatter_lines(text):
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if not lines or lines[0].strip() != "---":
        return []
    for j in range(1, len(lines)):
        if lines[j].strip() in ("---", "..."):
            return lines[1:j]
    return []


def frontmatter_value(text, key):
    """The scalar value of a top-level key: plain, quoted, or a | / > block. None if absent."""
    lines = frontmatter_lines(text)
    for i, line in enumerate(lines):
        m = re.match(re.escape(key) + r"[ \t]*:(.*)$", line)
        if not m:
            continue
        raw = m.group(1).strip()
        cont = []
        for nxt in lines[i + 1:]:
            if nxt.strip() and not nxt[:1].isspace():
                break
            cont.append(nxt.strip())
        while cont and not cont[-1]:
            cont.pop()
        if raw[:1] in ("|", ">"):
            parts = cont
            if raw[0] == "|":
                return "\n".join(parts).strip()
            return " ".join(p for p in parts if p).strip()
        if raw.startswith('"'):
            joined = " ".join([raw] + [c for c in cont if c])
            try:
                end = _double_quoted_end(joined)
                return json.loads(joined[:end + 1])
            except ValueError:
                return joined.strip('"')
        if raw.startswith("'"):
            joined = " ".join([raw] + [c for c in cont if c])
            body = joined[1:]
            out, k = [], 0
            while k < len(body):
                if body[k] == "'":
                    if body[k + 1:k + 2] == "'":
                        out.append("'")
                        k += 2
                        continue
                    break
                out.append(body[k])
                k += 1
            return "".join(out)
        raw = re.sub(r"[ \t]+#.*$", "", raw)
        return " ".join([raw] + [c for c in cont if c]).strip()
    return None


def _double_quoted_end(s):
    k = 1
    while k < len(s):
        if s[k] == "\\":
            k += 2
            continue
        if s[k] == '"':
            return k
        k += 1
    raise ValueError("unterminated string")


def yaml_scalar(value):
    """A one-line YAML scalar: plain when that is unambiguous, else double-quoted."""
    plain_ok = (value and value == value.strip() and "\n" not in value
                and not re.search(r":(\s|$)|\s#|[\x00-\x1f]", value)
                and value[0] not in "-?:,[]{}#&*!|>'\"%@`"
                and value.lower() not in ("true", "false", "yes", "no", "on", "off", "null", "~"))
    return value if plain_ok else json.dumps(value, ensure_ascii=False)


def render(name, description, hint):
    invocation = f"${name}"
    if hint and "`" not in hint and "\n" not in hint:
        invocation += f" {hint}"
    return TEMPLATE.format(name=name, description=yaml_scalar(description), invocation=invocation, marker=MARKER,
                           copyright=COPYRIGHT)


# ---------------------------------------------------------------------------
def read_text(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except (OSError, UnicodeDecodeError):
        return None


def links_to_command(text, name):
    return re.search(r"\]\([^)\s]*\.claude/commands/" + re.escape(name) + r"\.md[)#\s]", text) is not None


def parse_args(argv):
    p = argparse.ArgumentParser(description="Write .agents/skills/<name>/SKILL.md wrappers for .claude/commands/*.md.")
    p.add_argument("--repo", metavar="PATH", default=".", help="repository root (default: the current directory)")
    p.add_argument("--check", action="store_true", help="dry run: report, write nothing")
    p.add_argument("--force-wrappers", action="store_true",
                   help="replace a conflicting wrapper, renaming the old one to SKILL.md.pre-agent-kit first")
    return p.parse_args(argv)


def main(argv):
    args = parse_args(argv)
    root = args.repo
    cmd_dir = os.path.join(root, CMD_DIR)
    skill_dir = os.path.join(root, SKILL_DIR)
    if not os.path.isdir(cmd_dir):
        print(f"error: {CMD_DIR} not found under {root}")
        return 1
    would = "would " if args.check else ""

    claude_only = set()
    allow_path = os.path.join(root, ALLOW_FILE)
    if os.path.isfile(allow_path):
        text = read_text(allow_path)
        if text is None:
            print(f"error: {ALLOW_FILE} cannot be read as UTF-8")
            return 1
        for line in text.splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                claude_only.add(line)

    commands = sorted(f[:-3] for f in os.listdir(cmd_dir)
                      if f.endswith(".md") and os.path.isfile(os.path.join(cmd_dir, f)))
    results = []  # (status, path, detail)

    for c in sorted(claude_only - set(commands)):
        print(f"warning: {ALLOW_FILE} lists '{c}', which has no command")

    for name in commands:
        rel = f"{SKILL_DIR}/{name}/SKILL.md"
        wdir = os.path.join(skill_dir, name)
        wpath = os.path.join(wdir, "SKILL.md")
        if name in claude_only:
            existing = read_text(wpath) if os.path.isfile(wpath) else None
            if existing is not None and MARKER in existing:
                results.append(("stale", rel, f"'{name}' is Claude-only; suggest renaming it to SKILL.md{BACKUP_SUFFIX}"))
            else:
                results.append(("skipped", rel, "listed in " + ALLOW_FILE))
            continue
        if not NAME_RE.match(name):
            results.append(("error", rel, f"command file name '{name}.md' is not a valid skill name"))
            continue
        cmd_text = read_text(os.path.join(cmd_dir, name + ".md"))
        if cmd_text is None:
            results.append(("error", rel, f"{CMD_DIR}/{name}.md cannot be read as UTF-8"))
            continue
        description = frontmatter_value(cmd_text, "description")
        if not description:
            results.append(("error", rel, f"{CMD_DIR}/{name}.md has no description: frontmatter"))
            continue
        want = render(name, description, frontmatter_value(cmd_text, "argument-hint"))

        if os.path.lexists(wdir) and (os.path.islink(wdir) or not os.path.isdir(wdir)):
            results.append(("conflict", rel, f"{SKILL_DIR}/{name} is a symlink or a file; fix it by hand"))
            continue
        if not os.path.lexists(wpath):
            if not args.check:
                os.makedirs(wdir, exist_ok=True)
                with open(wpath, "w", encoding="utf-8", newline="\n") as f:
                    f.write(want)
            results.append((would + "create", rel, ""))
            continue
        have = None if os.path.islink(wpath) else read_text(wpath)
        if have == want:
            results.append(("unchanged", rel, ""))
            continue
        if have is not None and MARKER in have:
            if not args.check:
                with open(wpath, "w", encoding="utf-8", newline="\n") as f:
                    f.write(want)
            results.append((would + "update", rel, ""))
            continue
        if not args.force_wrappers:
            results.append(("conflict", rel, "not made by this script; left untouched "
                                             "(--force-wrappers backs it up and replaces it)"))
            continue
        backup = wpath + BACKUP_SUFFIX
        if os.path.lexists(backup):
            results.append(("conflict", rel, f"SKILL.md{BACKUP_SUFFIX} already exists; resolve that one by hand first"))
            continue
        if not args.check:
            os.rename(wpath, backup)
            with open(wpath, "w", encoding="utf-8", newline="\n") as f:
                f.write(want)
        results.append((would + "replace", rel, f"old wrapper saved as SKILL.md{BACKUP_SUFFIX}"))

    # Wrappers whose command is gone. Native skills (no marker, no command link) are ignored.
    if os.path.isdir(skill_dir):
        for d in sorted(os.listdir(skill_dir)):
            wpath = os.path.join(skill_dir, d, "SKILL.md")
            if d in commands or not os.path.isfile(wpath):
                continue
            text = read_text(wpath) or ""
            if MARKER in text or links_to_command(text, d):
                rel = f"{SKILL_DIR}/{d}/SKILL.md"
                results.append(("stale", rel, f"{CMD_DIR}/{d}.md no longer exists; suggest renaming it to "
                                              f"{rel}{BACKUP_SUFFIX}"))

    for status, rel, detail in results:
        print(f"{status}: {rel}" + (f" ({detail})" if detail else ""))
    tally = {}
    for status, _rel, _detail in results:
        tally[status] = tally.get(status, 0) + 1
    print("summary: " + (", ".join(f"{n} {s}" for s, n in sorted(tally.items())) or "no commands"))

    bad = {"stale", "conflict", "error"}
    if args.check:
        bad |= {"would create", "would update", "would replace"}
    return 1 if any(s in bad for s, _r, _d in results) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
